// Generates the exactness vectors for the synthetic orbiter blob (EPHEM kind 4):
// a reproducible set of queries and the bit-exact answers of the WebAssembly
// build. Run it only when that blob, the format, or the library's arithmetic
// changes on purpose. It writes only test/vectors/orbiter.*; the other vectors
// belong to tools/make-vectors.mjs.
//
//   node tools/make-vectors-orbiter.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { load, runAll, prng, toHex, root } from '../test/harness.mjs';

const name = 'orbiter';
const blob = new Uint8Array(readFileSync(resolve(root, `test/blobs/${name}.slb`)));
const report = JSON.parse(readFileSync(resolve(root, `test/blobs/${name}.report.json`), 'utf8'));
const api = await load(blob);
const rnd = prng(20261121);
const [w0, w1] = report.windowEt;
const pick = (a) => a[Math.floor(rnd() * a.length)];
const between = (a, b) => a + (b - a) * rnd();
const q = ['# spice-lite exactness queries for the ' + name + ' blob (synthetic orbiters, EPHEM kind 4); generated by tools/make-vectors-orbiter.mjs'];

const orbiters = report.ephem.filter((s) => s.kind === 4);
const all = [3, 301, 399, ...orbiters.map((s) => s.target)];
// each orbiter from its own center, then every pairing, at random times
for (const s of orbiters) for (let i = 0; i < 24; i++) q.push(`state ${s.target} ${s.center} ${toHex(between(w0, w1))} 0`);
for (let i = 0; i < 48; i++) q.push(`state ${pick(all)} ${pick(all)} ${toHex(between(w0, w1))} 0`);
// record boundaries: the grid point itself and its two neighbors in floating point
for (const s of orbiters) {
  for (const k of [0, 1, Math.floor(s.recordCount / 2), s.recordCount - 1, s.recordCount]) {
    const t = s.tStart + k * s.interval;
    const f = new Float64Array([t]), u = new BigInt64Array(f.buffer);
    const step = (d) => { u[0] += d; const v = f[0]; u[0] -= d; return v; };
    for (const tt of [step(t < 0 ? 1n : -1n), t, step(t < 0 ? -1n : 1n)]) q.push(`state ${s.target} ${s.center} ${toHex(tt)} 0`);
  }
  q.push(`state ${s.target} ${s.center} ${toHex(w0 - 1)} 0`, `state ${s.target} ${s.center} ${toHex(w1 + 1)} 0`);
}
// the tree is rooted at the Earth-Moon barycenter, so corrections are unsupported
q.push(`state -9001 399 ${toHex(w0 + 1000)} 1`, `state 301 -9002 ${toHex(w0 + 1000)} 2`, `state -9001 5 ${toHex(w0 + 1000)} 0`);
// supplied state for the body flagged as the spacecraft, against its kind 4 prediction
const t = w0 + 123456.5;
const pred = api.state(-9001, 399, t, 0).state;
q.push(`gap ${toHex(t)}`, `setstate -9001 399 ${toHex(t)} ${pred.map(toHex).join(' ')} ${toHex(20)}`);
for (const dt of [0, 1, 19.5, 20.5, -5, 300]) q.push(`state -9001 399 ${toHex(t + dt)} 0`, `state -9001 301 ${toHex(t + dt)} 0`);
q.push(`gap ${toHex(t)}`, `gap ${toHex(t + 10)}`, `gap ${toHex(t + 100)}`, `setstate -9002 301 ${toHex(t)} ${pred.map(toHex).join(' ')} ${toHex(20)}`, 'clearstate', `state -9001 399 ${toHex(t + 1)} 0`);

const queries = q.join('\n') + '\n';
const fresh = await load(blob);
writeFileSync(resolve(root, `test/vectors/${name}.queries`), queries);
writeFileSync(resolve(root, `test/vectors/${name}.expected`), runAll(fresh, queries));
console.log(`${q.length - 1} queries written`);
