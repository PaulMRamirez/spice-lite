// Generates the exactness vectors for lite_sub_point and lite_occulted: a
// reproducible set of queries against the two geometry blobs and the bit-exact
// answers of the WebAssembly build. Run it only when those blobs, the format,
// or the library's arithmetic changes on purpose; test/geometry.test.mjs then
// holds every host and build to these bits. Needs no kernels: where a query
// wants a spacecraft near a limb, the position comes from the library's own
// body states.
//
//   node tools/make-vectors-geometry.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { load, runAll, prng, toHex, root } from '../test/harness.mjs';

const sub = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const norm = (a) => Math.hypot(a[0], a[1], a[2]);
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];

async function make(name, build) {
  const blob = new Uint8Array(readFileSync(resolve(root, `test/blobs/${name}.slb`)));
  const report = JSON.parse(readFileSync(resolve(root, `test/blobs/${name}.report.json`), 'utf8'));
  const api = await load(blob);
  const q = [`# spice-lite geometry queries for the ${name} blob; generated by tools/make-vectors-geometry.mjs`];
  build(q, api, report);
  const queries = q.join('\n') + '\n';
  writeFileSync(resolve(root, `test/vectors/${name}.queries`), queries);
  writeFileSync(resolve(root, `test/vectors/${name}.expected`), runAll(await load(blob), queries));
  console.log(`${name}: ${q.length - 1} queries written`);
}

await make('eclipses', (q, api, report) => {
  const rnd = prng(20261121);
  const [w0, w1] = report.windowEt;
  const pick = (a) => a[Math.floor(rnd() * a.length)];
  const between = (a, b) => a + (b - a) * rnd();
  const SC = -900;
  // sub-points between natural bodies; 4 is the triaxial stand-in
  for (let i = 0; i < 36; i++) {
    const body = pick([399, 301, 4]);
    q.push(`subpoint ${body} ${pick([10, 301, 399, 4, 3, 0].filter((b) => b !== body))} ${toHex(between(w0, w1))}`);
  }
  // occultation among the Sun, Earth, and Moon: across the window, then every
  // ten minutes through the solar eclipse of October 14 and the lunar eclipse of
  // October 28 (about 1.1 and 15.1 days into the window)
  for (let i = 0; i < 12; i++) q.push(`occulted ${pick([10, 301, 399])} ${pick([10, 301, 399, 4])} ${pick([10, 301, 399, 0])} ${toHex(between(w0, w1))}`);
  for (let k = 0; k <= 24; k++) q.push(`occulted 399 301 10 ${toHex(w0 + 1.04 * 86400 + 600 * k)}`);
  for (let k = 0; k <= 36; k++) {
    const t = toHex(w0 + 15.0 * 86400 + 600 * k);
    q.push(`occulted 301 399 10 ${t}`, `occulted 10 399 301 ${t}`);
  }
  // a spacecraft placed around each body with radii: sub-points from a meter up
  // to a million kilometers, on the axes and off them
  const t = w0 + 5 * 86400 + 0.25;
  for (const body of [399, 301, 4]) {
    for (let i = 0; i < 14; i++) {
      const z = 2 * rnd() - 1, az = 2 * Math.PI * rnd(), c = Math.sqrt(1 - z * z);
      const d = i < 3 ? [0, 1, 2].map((k) => (k === i ? 1 : 0)) : [c * Math.cos(az), c * Math.sin(az), z];
      const r = { 399: 6378.2, 301: 1737.5, 4: 13.1 }[body] + 10 ** (-3 + 9 * rnd());
      q.push(`setstate ${SC} ${body} ${toHex(t)} ${d.map((v) => toHex(v * r)).join(' ')} ${toHex(0)} ${toHex(0)} ${toHex(0)} ${toHex(60)}`);
      q.push(`subpoint ${body} ${SC} ${toHex(t + i)}`);
    }
    // inside the body, and at its center
    q.push(`setstate ${SC} ${body} ${toHex(t)} ${toHex(1)} ${toHex(2)} ${toHex(3)} ${toHex(0)} ${toHex(0)} ${toHex(0)} ${toHex(60)}`, `subpoint ${body} ${SC} ${toHex(t)}`);
    q.push(`setstate ${SC} ${body} ${toHex(t)} ${Array(6).fill(toHex(0)).join(' ')} ${toHex(60)}`, `subpoint ${body} ${SC} ${toHex(t)}`, `occulted 10 ${body} ${SC} ${toHex(t)}`);
  }
  // the spacecraft near the limb: behind the front body on the line from the
  // back one, then stepped sideways through every code
  for (const [front, back, dist] of [[301, 10, 300000], [301, 10, 500000], [399, 10, 900000], [399, 301, 20000], [301, 399, 40000], [4, 10, 5000]]) {
    const pf = api.state(front, 0, t, 0).state.slice(0, 3), pb = api.state(back, 0, t, 0).state.slice(0, 3);
    const axis = sub(pf, pb), u = axis.map((v) => v / norm(axis));
    let w = cross(u, [0.3, -0.5, 0.8]); w = w.map((v) => v / norm(w));
    for (let k = 0; k <= 12; k++) {
      const phi = 0.001 * k * k * (front === 4 ? 0.05 : 1);
      const o = pf.map((v, i) => v + dist * (Math.cos(phi) * u[i] + Math.sin(phi) * w[i]));
      q.push(`setstate ${SC} 0 ${toHex(t)} ${o.map(toHex).join(' ')} ${toHex(0)} ${toHex(0)} ${toHex(0)} ${toHex(60)}`);
      q.push(`occulted ${back} ${front} ${SC} ${toHex(t)}`, `occulted ${front} ${back} ${SC} ${toHex(t)}`);
    }
  }
  q.push('clearstate', `subpoint 399 ${SC} ${toHex(t)}`, `occulted 10 301 ${SC} ${toHex(t)}`);
  // requests that get status codes: no radii, no orientation, the body itself,
  // unknown bodies, outside the window
  q.push(`subpoint 3 10 ${toHex(t)}`, `subpoint 10 399 ${toHex(t)}`, `subpoint 399 399 ${toHex(t)}`, `subpoint 399 3 ${toHex(t)}`, `subpoint 499 10 ${toHex(t)}`, `subpoint 399 301 ${toHex(w0 - 1)}`, `subpoint 399 301 ${toHex(w1 + 86400)}`);
  q.push(`occulted 10 3 399 ${toHex(t)}`, `occulted 10 10 399 ${toHex(t)}`, `occulted 10 301 301 ${toHex(t)}`, `occulted 10 399 3 ${toHex(t)}`, `occulted 10 499 399 ${toHex(t)}`, `occulted 10 301 399 ${toHex(w0 - 1)}`);
});

await make('saturn-soi', (q, api, report) => {
  const rnd = prng(699);
  const [w0, w1] = report.windowEt;
  const between = (a, b) => a + (b - a) * rnd();
  for (let i = 0; i < 30; i++) q.push(`subpoint 699 ${[-82, -82, -82, 399, 10, 6][i % 6]} ${toHex(between(w0, w1))}`);
  for (let i = 0; i < 6; i++) q.push(`subpoint 399 ${[-82, 10, 699][i % 3]} ${toHex(between(w0, w1))}`);
  // every five minutes through the hours in which Saturn hides the Sun and the
  // Earth from the spacecraft (about 15.5 to 16.3 hours into the window)
  for (let k = 0; k <= 24; k++) {
    const t = toHex(w0 + 14.5 * 3600 + 300 * k);
    q.push(`occulted 10 699 -82 ${t}`, `occulted 399 699 -82 ${t}`, `occulted 699 10 -82 ${t}`);
  }
  q.push(`occulted 10 699 399 ${toHex(w0 + 100)}`, `occulted 10 6 -82 ${toHex(w0 + 100)}`, `subpoint 6 -82 ${toHex(w0 + 100)}`, `subpoint 699 -82 ${toHex(w1 + 700)}`);
});
