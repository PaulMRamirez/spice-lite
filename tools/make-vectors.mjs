// Generates the exactness vectors: a reproducible set of queries against the
// test blob and the bit-exact answers of the WebAssembly build. Run it only
// when the blob, the format, or the library's arithmetic changes on purpose;
// the tests then hold every host and build to these bits.
//
//   node tools/make-vectors.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { load, runAll, prng, toHex, root } from '../test/harness.mjs';

const name = 'cassini-soi';
const blob = new Uint8Array(readFileSync(resolve(root, `test/blobs/${name}.slb`)));
const report = JSON.parse(readFileSync(resolve(root, `test/blobs/${name}.report.json`), 'utf8'));
const api = await load(blob);
const rnd = prng(20261120);
const [w0, w1] = report.windowEt;
const sc = report.ephem.find((s) => s.target === -82);
const [s0, s1] = [sc.tStart, sc.tStart + sc.recordCount * sc.interval];
const pick = (a) => a[Math.floor(rnd() * a.length)];
const between = (a, b) => a + (b - a) * rnd();
const q = ['# spice-lite exactness queries for the ' + name + ' blob; generated by tools/make-vectors.mjs'];

const natural = [0, 3, 6, 10, 301, 399];
for (let i = 0; i < 48; i++) q.push(`state ${pick(natural)} ${pick(natural)} ${toHex(between(w0, w1))} ${i % 3}`);
for (let i = 0; i < 18; i++) q.push(`state ${i % 2 ? -82 : pick(natural)} ${i % 2 ? pick(natural) : -82} ${toHex(between(s0, s1))} ${i % 3}`);
// edges: exact window ends, just outside, unknown bodies, bad correction code
for (const t of [w0, w1, w0 - 1, w1 + 1, s0, s1, s1 + 1]) q.push(`state 301 399 ${toHex(t)} 0`, `state -82 6 ${toHex(t)} 0`);
q.push(`state 5 399 ${toHex(w0 + 10)} 0`, `state 301 301 ${toHex(w0 + 10)} 0`, `state 301 399 ${toHex(w0 + 10)} 7`);
for (let i = 0; i < 12; i++) q.push(`orient ${i % 2 ? 301 : 399} ${toHex(between(w0, w1))}`);
q.push(`orient 10 ${toHex(w0 + 10)}`, `orient 301 ${toHex(w1 + 5)}`);
for (let i = 0; i < 12; i++) q.push(`siteview ${1 + (i % 2)} ${pick([10, 301, 399, 6])} ${toHex(between(w0, w1))} 0`);
q.push(`siteview 1 -82 ${toHex(between(s0, s1))} 0`, `siteview 9 10 ${toHex(w0 + 10)} 0`, `siteview 1 10 ${toHex(w0 + 10)} 1`);
q.push('host2et 3 0 0', 'host2et 3 100 500000', 'host2et 3 999999 999999', 'host2et 3 1000000 0', 'host2et 3 2500000 250000', 'host2et 2 100 0', 'host2et 3 100 1000000');
q.push('fwtime 00030000000064000001f4', 'fwtime 0003000000006400');
// supplied state: take the predicted state at t, hand it back, and query around it
const t = s0 + 40000.5;
const pred = api.state(-82, 6, t, 0).state;
const viaEarth = api.state(-82, 399, t, 0).state;
q.push(`gap ${toHex(t)}`);
q.push(`setstate -82 6 ${toHex(t)} ${pred.map(toHex).join(' ')} ${toHex(30)}`);
for (const dt of [0, 1, 5, 29.5, 30.5, -10, 100]) q.push(`state -82 6 ${toHex(t + dt)} 0`, `state -82 399 ${toHex(t + dt)} ${dt === 5 ? 1 : 0}`);
q.push(`gap ${toHex(t)}`, `gap ${toHex(t + 12)}`, `gap ${toHex(t + 300)}`);
q.push(`setstate -82 399 ${toHex(t)} ${viaEarth.map(toHex).join(' ')} ${toHex(60)}`);
q.push(`state -82 6 ${toHex(t + 20)} 0`, `state 10 -82 ${toHex(t + 20)} 2`, `gap ${toHex(t + 20)}`);
q.push(`setstate 301 399 ${toHex(t)} ${pred.map(toHex).join(' ')} ${toHex(30)}`, `setstate -82 -82 ${toHex(t)} ${pred.map(toHex).join(' ')} ${toHex(30)}`);
q.push('clearstate', `state -82 6 ${toHex(t + 1)} 0`, `gap ${toHex(t)}`);

const queries = q.join('\n') + '\n';
const fresh = await load(blob);
writeFileSync(resolve(root, `test/vectors/${name}.queries`), queries);
writeFileSync(resolve(root, `test/vectors/${name}.expected`), runAll(fresh, queries));
console.log(`${q.length - 1} queries written`);
